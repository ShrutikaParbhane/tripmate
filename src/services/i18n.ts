/**
 * Translation helper function with fallback to English
 */
export function translate(key: string, lang: Language = 'en'): string {
  const langDict = TRANSLATIONS[lang] || TRANSLATIONS.en;
  return langDict[key] || TRANSLATIONS.en[key] || key;
}

/**
 * Format currency in Indian Rupees ₹ (e.g., ₹80,000) with locale awareness
 */
export function formatINR(amount: number): string {
  return new Intl.NumberFormat('en-IN', {
    style: 'currency',
    currency: 'INR',
    maximumFractionDigits: 0,
  }).format(amount);
}

/**
 * Format date string into locale display date
 */
export function formatDate(dateString: string, lang: Language = 'en'): string {
  try {
    const d = new Date(dateString);
    const localeMap: Record<Language, string> = {
      en: 'en-IN',
      hi: 'hi-IN',
      mr: 'mr-IN',
      ta: 'ta-IN',
      te: 'te-IN',
      bn: 'bn-IN',
      gu: 'gu-IN',
      kn: 'kn-IN',
      es: 'es-ES',
      fr: 'fr-FR',
    };
    return d.toLocaleDateString(localeMap[lang] || 'en-IN', {
      day: 'numeric',
      month: 'short',
      year: 'numeric',
    });
  } catch {
    return dateString;
  }
}
